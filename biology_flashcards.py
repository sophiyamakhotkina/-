def show_card(card, number=None, total=None):
    """Print one card's question and answer."""
    if number is not None:
        print(f"\nКарточка {number}/{total}")
    print(f"Тема: {card['topic']}")
    print("\nВОПРОС:")
    print(textwrap.fill(card["question"], width=78))
    input("\nНажми Enter, чтобы открыть ответ...")
    print("\nОТВЕТ:")
    print(textwrap.fill(card["answer"], width=78))


def flashcards(cards):
    """Study cards in flashcard mode."""
    deck = cards[:]
    random.shuffle(deck)
    for i, card in enumerate(deck, start=1):
        show_card(card, i, len(deck))
        if i < len(deck):
            again = input("\nEnter — следующая карточка; q — выйти: ").strip().lower()
            if again == "q":
                break
    print("\nРежим карточек завершён.")


def keyword_quiz(cards):
    """Ask questions and give gentle keyword-based feedback."""
    deck = cards[:]
    random.shuffle(deck)
    correct = 0

    for i, card in enumerate(deck, start=1):
        print(f"\nВопрос {i}/{len(deck)} | {card['topic']}")
        print(textwrap.fill(card["question"], width=78))
        user_answer = input("\nТвой ответ: ").strip().lower()

        # A card is counted as correct when at least half of its keywords appear.
        keywords = card["keywords"]
        hits = sum(1 for word in keywords if word.lower() in user_answer)
        needed = max(1, (len(keywords) + 1) // 2)

        if hits >= needed:
            print("Хорошо! Похоже, основные понятия ты назвала.")
            correct += 1
        else:
            print("Стоит повторить эту карточку.")
        print("\nПравильный ответ:")
        print(textwrap.fill(card["answer"], width=78))

        if i < len(deck):
            choice = input("\nEnter — дальше; q — завершить квиз: ").strip().lower()
            if choice == "q":
                break

    print(f"\nРезультат: {correct} из {i} карточек отмечены как верные.")
    print("Проверка по ключевым словам приблизительная: сравнивай смысл ответа, а не только слова.")


def choose_topic(cards):
    """Let the learner select one animal group."""
    topics = sorted({card["topic"] for card in cards})
    print("\nТемы:")
    for index, topic in enumerate(topics, start=1):
        print(f"{index}. {topic}")
    print("0. Все темы")

    choice = input("\nНомер темы: ").strip()
    if choice == "0":
        return cards
    if choice.isdigit() and 1 <= int(choice) <= len(topics):
        selected_topic = topics[int(choice) - 1]
        return [card for card in cards if card["topic"] == selected_topic]

    print("Не получилось распознать выбор. Будут использованы все темы.")
    return cards


def main():
    """Main menu."""
    print("=" * 58)
    print("БИОЛОГИЯ: ИНТЕРАКТИВНЫЕ КАРТОЧКИ")
    print("Системы органов животных разных классов")
    print("=" * 58)

    while True:
        print("\nВыбери режим:")
        print("1. Карточки: вопрос → ответ")
        print("2. Квиз: ответь самостоятельно")
        print("3. Количество карточек и темы")
        print("0. Выход")

        mode = input("\nТвой выбор: ").strip()
        if mode == "0":
            print("Удачи в изучении биологии!")
            break
        elif mode in ("1", "2"):
            selected_cards = choose_topic(CARDS)
            if mode == "1":
                flashcards(selected_cards)
            else:
                keyword_quiz(selected_cards)
        elif mode == "3":
            print(f"\nВсего карточек: {len(CARDS)}")
            print("Темы: " + ", ".join(sorted({c['topic'] for c in CARDS})))
        else:
            print("Выбери 1, 2, 3 или 0.")


if __name__ == "__main__":
    main()
